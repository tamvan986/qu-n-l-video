/**
 * Helper to determine tree stage from tick count
 */
export function getStageFromTicks(completedTicks: number): TreeStageKey {
  if (completedTicks >= 6) return 'trai';
  if (completedTicks === 5) return 'hoa';
  if (completedTicks === 4) return 'la';
  if (completedTicks === 3) return 'choinon';
  if (completedTicks === 2) return 'mamxanh';
  return 'hatmam';
}

/**
 * Helper to determine tree stage from total accumulated points
 */
export function getStageFromPoints(points: number): TreeStageKey {
  if (points >= 30) return 'trai';
  if (points >= 25) return 'hoa';
  if (points >= 20) return 'la';
  if (points >= 15) return 'choinon';
  if (points >= 10) return 'mamxanh';
  return 'hatmam';
}

